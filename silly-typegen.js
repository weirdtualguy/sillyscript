#!/usr/bin/env node
// silly-typegen.js — TypeScript Type Generator for SilverScript Artifacts (sillyscript)
//
// Ingests SilverScript .json artifacts produced by silverc and generates
// strongly-typed TypeScript definitions (.d.ts) for:
//   - Declared structs & contract runtime state
//   - Named entry argument interfaces & positional tuple types
//   - Entrypoint registry with compile-time dispatch tag literals
//   - Type-safe Contract wrapper class

const fs = require('fs');
const path = require('path');

/**
 * Maps a SilverScript TypeRef to a TypeScript type string
 */
function toTsType(type, prefix = '') {
  switch (type.kind) {
    case 'int':
    case 'temporal':
      return 'bigint';
    case 'bool':
      return 'boolean';
    case 'byte':
      return 'number';
    case 'string':
      return 'string';
    case 'pubkey':
    case 'sig':
    case 'datasig':
    case 'fixed_bytes':
    case 'bytes':
      return 'Uint8Array | Buffer | string';
    case 'fixed_array':
    case 'dynamic_array':
      return `Array<${toTsType(type.item, prefix)}>`;
    case 'struct':
      return prefix + sanitizeIdentifier(type.name);
    default:
      return 'unknown';
  }
}

function sanitizeIdentifier(name) {
  return name.replace(/[^a-zA-Z0-9_$]/g, '_');
}

function capitalize(name) {
  if (!name) return '';
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/**
 * Generates TypeScript declaration code for an artifact
 * @param {string|object} artifactOrPath - Path to JSON file or parsed artifact object
 * @param {object} [opts]
 * @param {string} [opts.importPath='sillyscript'] - Module specifier to import Contract from
 * @returns {string} TypeScript declaration code
 */
function generateTypes(artifactOrPath, opts = {}) {
  let artifact;
  if (typeof artifactOrPath === 'string') {
    artifact = JSON.parse(fs.readFileSync(artifactOrPath, 'utf8'));
  } else if (typeof artifactOrPath === 'object' && artifactOrPath !== null) {
    artifact = artifactOrPath;
  } else {
    throw new Error('generateTypes: expected file path or parsed artifact object');
  }

  const importPath = opts.importPath || 'sillyscript';
  const out = [];

  out.push('// Auto-generated by sillyscript typegen — DO NOT EDIT DIRECTLY');
  out.push('');
  out.push(`import { Contract } from '${importPath}';`);
  out.push('');

  // 1. Emit common declared structs
  const structs = artifact.structs || {};
  for (const [structName, structDef] of Object.entries(structs)) {
    const sName = sanitizeIdentifier(structName);
    out.push(`export interface ${sName} {`);
    for (const field of structDef.fields || []) {
      out.push(`  ${sanitizeIdentifier(field.name)}: ${toTsType(field.type)};`);
    }
    out.push('}');
    out.push('');
  }

  // 2. Emit per-contract definitions
  const contracts = artifact.contracts || {};
  for (const [contractName, contractDef] of Object.entries(contracts)) {
    const cName = sanitizeIdentifier(contractName);
    const stateName = `${cName}State`;
    const entriesMapName = `${cName}Entries`;
    const wrapperName = `${cName}Contract`;

    // Runtime State Interface
    const stateFields = (contractDef.runtime_state && contractDef.runtime_state.fields) || [];
    out.push(`export interface ${stateName} {`);
    if (stateFields.length === 0) {
      out.push('  // stateless contract');
    } else {
      for (const field of stateFields) {
        out.push(`  ${sanitizeIdentifier(field.name)}: ${toTsType(field.type)};`);
      }
    }
    out.push('}');
    out.push('');

    // Entries and arguments
    const entries = contractDef.entries || {};
    const entryNames = Object.keys(entries);

    for (const [entryName, entryDef] of Object.entries(entries)) {
      const eName = sanitizeIdentifier(entryName);
      const argsInterfaceName = `${cName}${capitalize(eName)}Args`;
      const tupleTypeName = `${cName}${capitalize(eName)}Tuple`;
      const params = entryDef.params || [];

      // Named args interface
      out.push(`export interface ${argsInterfaceName} {`);
      for (const p of params) {
        out.push(`  ${sanitizeIdentifier(p.name)}: ${toTsType(p.type)};`);
      }
      out.push('}');
      out.push('');

      // Positional tuple type
      const tupleElements = params.map(p => `${sanitizeIdentifier(p.name)}: ${toTsType(p.type)}`).join(', ');
      out.push(`export type ${tupleTypeName} = [${tupleElements}];`);
      out.push('');
    }

    // Entries map interface
    out.push(`export interface ${entriesMapName} {`);
    for (const [entryName, entryDef] of Object.entries(entries)) {
      const eName = sanitizeIdentifier(entryName);
      const argsInterfaceName = `${cName}${capitalize(eName)}Args`;
      const tupleTypeName = `${cName}${capitalize(eName)}Tuple`;
      const tag = entryDef.dispatch_tag || '';

      out.push(`  ${eName}: {`);
      out.push(`    args: ${argsInterfaceName};`);
      out.push(`    tuple: ${tupleTypeName};`);
      out.push(`    tag: '${tag}';`);
      out.push('  };');
    }
    out.push('}');
    out.push('');

    // Typed Contract Wrapper Class
    out.push(`export class ${wrapperName} extends Contract {`);
    out.push(`  readonly state: ${stateName};`);
    out.push(`  setState(state: ${stateName}): this;`);
    out.push(`  decodeState(scriptOrRedeem?: Buffer | string): ${stateName};`);
    out.push(`  encodeState(stateValues: ${stateName}): Buffer;`);
    out.push(`  buildRedeem(stateValues: ${stateName}): Buffer;`);
    out.push(`  nextScriptPubKey(stateValues: ${stateName}): Buffer;`);
    out.push(`  nextAddress(stateValues: ${stateName}, network?: string): string;`);
    out.push('');
    out.push(`  buildSigScript<K extends keyof ${entriesMapName}>(`);
    out.push(`    entryName: K,`);
    out.push(`    args: ${entriesMapName}[K]['args'] | ${entriesMapName}[K]['tuple'],`);
    out.push(`    redeemScript?: Buffer`);
    out.push(`  ): Buffer;`);
    out.push('');
    out.push(`  populateInput<K extends keyof ${entriesMapName}>(`);
    out.push(`    tx: any,`);
    out.push(`    inputIndex: number,`);
    out.push(`    opts: {`);
    out.push(`      entryName: K;`);
    out.push(`      args: ${entriesMapName}[K]['args'] | ${entriesMapName}[K]['tuple'];`);
    out.push(`      privKey?: Buffer;`);
    out.push(`      redeemScript?: Buffer;`);
    out.push(`    }`);
    out.push(`  ): any;`);
    out.push('');
    out.push(`  addContinuationOutput(`);
    out.push(`    tx: any,`);
    out.push(`    outputIndex: number,`);
    out.push(`    authInputIndex: number,`);
    out.push(`    nextState: ${stateName},`);
    out.push(`    amount: bigint,`);
    out.push(`    covenantIdHex: string`);
    out.push(`  ): any;`);
    out.push('');
    out.push(`  addGenesisOutput(`);
    out.push(`    tx: any,`);
    out.push(`    outputIndex: number,`);
    out.push(`    authInputIndex: number,`);
    out.push(`    initialState: ${stateName},`);
    out.push(`    amount: bigint`);
    out.push(`  ): { amount: bigint; script: string; covenantId: string; };`);
    out.push('}');
    out.push('');
  }

  return out.join('\n');
}

module.exports = { generateTypes, toTsType };

// ─────────────────────────────────────────────────────────────────────────────
// CLI Runner & Self-test
// ─────────────────────────────────────────────────────────────────────────────

function cli() {
  const args = process.argv.slice(2);

  if (args.includes('--test')) {
    let pass = 0, fail = 0;
    const t = (label, cond, detail) => {
      if (cond) pass++; else fail++;
      console.log((cond ? 'PASS' : 'FAIL') + '  ' + label + (detail && !cond ? '  ' + detail : ''));
    };

    // Test scalar mapping
    t('type int -> bigint', toTsType({ kind: 'int' }) === 'bigint');
    t('type temporal -> bigint', toTsType({ kind: 'temporal' }) === 'bigint');
    t('type bool -> boolean', toTsType({ kind: 'bool' }) === 'boolean');
    t('type byte -> number', toTsType({ kind: 'byte' }) === 'number');
    t('type string -> string', toTsType({ kind: 'string' }) === 'string');
    t('type pubkey -> buffer union', toTsType({ kind: 'pubkey' }) === 'Uint8Array | Buffer | string');
    t('type array -> Array<bigint>', toTsType({ kind: 'dynamic_array', item: { kind: 'int' } }) === 'Array<bigint>');

    // Test against vesting.json
    const vPath = path.join(__dirname, 'vesting.json');
    if (fs.existsSync(vPath)) {
      const code = generateTypes(vPath);
      t('generated code is non-empty', code.length > 200);
      t('includes VestingEscrowState', code.includes('export interface VestingEscrowState {'));
      t('state has claimed_so_far: bigint', code.includes('claimed_so_far: bigint;'));
      t('includes VestingEscrowClaimArgs', code.includes('export interface VestingEscrowClaimArgs {'));
      t('claim args has amount: bigint', code.includes('amount: bigint;'));
      t('claim args has claim_time: bigint', code.includes('claim_time: bigint;'));
      t('includes claim dispatch tag literal', code.includes("tag: 'cf696771';"));
      t('includes VestingEscrowContract class', code.includes('export class VestingEscrowContract extends Contract {'));
      t('includes addGenesisOutput', code.includes('addGenesisOutput('));
      t('covenantIdHex required', code.includes('covenantIdHex: string') && !code.includes('covenantIdHex?'));
    }

    console.log(fail ? `\n${fail} FAILURE(S)` : `\nALL ${pass} PASS`);
    process.exit(fail ? 1 : 0);
  }

  if (args.length === 0 || args.includes('-h') || args.includes('--help')) {
    console.log('Usage: silly-typegen <artifact.json> [--out <output.d.ts>] [--import <moduleName>]');
    process.exit(0);
  }

  const inputPath = args[0];
  let outPath = null;
  let importPath = 'sillyscript';

  for (let i = 1; i < args.length; i++) {
    if (args[i] === '--out' && i + 1 < args.length) outPath = args[++i];
    if (args[i] === '--import' && i + 1 < args.length) importPath = args[++i];
  }

  if (!fs.existsSync(inputPath)) {
    console.error(`Error: input file '${inputPath}' does not exist.`);
    process.exit(1);
  }

  const tsCode = generateTypes(inputPath, { importPath });

  if (outPath) {
    fs.writeFileSync(outPath, tsCode, 'utf8');
    console.log(`Generated TypeScript definitions at: ${outPath}`);
  } else {
    process.stdout.write(tsCode);
  }
}

if (require.main === module) {
  cli();
}
